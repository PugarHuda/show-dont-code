""".eln export: the run as one experiment in the ELN Consortium's file format (RO-Crate 1.2 in a zip with a single root
folder), which eLabFTW, RSpace, Kadi4Mat, SampleDB, PASTA and other electronic lab notebooks import.
Spec: https://github.com/TheELNConsortium/TheELNFileFormat

The experiment's body (`text`) is HTML a notebook shows as the entry: what the protocol came from, the steps with
volumes, the checks it passed, and the bench card drawings; every file of the run is attached, and each reviewer
finding becomes a comment on the entry.
"""
import hashlib
import html
import io
import json
import zipfile
from datetime import datetime, timezone
from pathlib import Path

from .crate import AUTHOR, BIOVL2, FORMATS, REPO

CC_BY = "https://creativecommons.org/licenses/by/4.0/"
RO12 = "https://w3id.org/ro/crate/1.2"
ELN_SPEC = "https://purl.archive.org/purl/elnconsortium/eln-spec/1.2+20260923"  # the newest ELN version
FORMATS = {**FORMATS, ".jpg": "image/jpeg", ".zip": "application/zip"}


def _iso(t=None):
    return datetime.fromtimestamp(t, timezone.utc).isoformat(timespec="seconds") if t else \
        datetime.now(timezone.utc).isoformat(timespec="seconds")


def _body(name, steps, rec, source, card, app_url):
    e = html.escape
    rows = "".join(
        f"<tr><td>{i + 1}</td><td>{e(s.get('description') or s.get('action', ''))}</td>"
        f"<td>{e(str(s['volume_ul']) + ' µL') if s.get('volume_ul') else ''}</td><td>{e(s.get('reagent') or '')}</td>"
        f"<td>{e(s.get('destination') or '')}</td>"
        f"<td>{'' if s.get('start') is None else f'{s["start"]:.0f}–{s["end"]:.0f} s'}</td></tr>"
        for i, s in enumerate(steps))
    src = (f'<a href="{e(source["url"])}">{e(source["title"])}</a> (protocols.io' +
           (f', doi:{e(source["doi"])})' if source.get("doi") else ")")) if source else \
        ("a first-person video of the protocol done by hand" + ("" if name.startswith("u-") else
                                                               f' (<a href="{BIOVL2}">BioVL2</a>, CC BY 4.0)'))
    rs = rec.get("opentrons_robot_server") or []
    checks = [f"Opentrons simulator: {'passed' if rec['simulator']['passed'] else 'failed'}",
              f"opentrons analyze: {'passed' if rec['opentrons_analysis']['passed'] else 'not run or failed'}"]
    checks += [f"Opentrons robot-server {r.get('robot_software')} (Flex simulation), {r.get('reactions')} reaction(s): "
               f"{r.get('status')}, {r.get('commands')} commands, matches its analysis: {r.get('matches_analysis')}" for r in rs]
    plr = rec.get("pylabrobot") or {}
    checks.append(f"PyLabRobot Hamilton STARlet: {'passed' if plr.get('hamilton_starlet_passed') else 'not passed'}; "
                  f"Tecan EVO: {'passed' if plr.get('tecan_evo_passed') else 'not passed'}")
    out = [f"<p>Opentrons Flex protocol generated by <a href=\"{REPO}\">Show, Don't Code</a> from {src}. "
           f"Open the run next to its source: <a href=\"{e(app_url)}\">{e(app_url)}</a>.</p>",
           "<h2>Steps</h2><table><thead><tr><th>#</th><th>Step</th><th>Volume</th><th>Reagent</th><th>Into</th>"
           f"<th>Video</th></tr></thead><tbody>{rows}</tbody></table>",
           "<h2>Checks</h2><ul>" + "".join(f"<li>{e(c)}</li>" for c in checks) + "</ul>",
           f"<p>protocol.py SHA-256 <code>{rec['protocol_sha256']}</code>; every model output is hashed in receipt.json.</p>"]
    if card:
        out.append(f"<h2>Bench card</h2><p>Each step's video frame redrawn by {e(card['image_model'])}, checked against "
                   f"the frame by {e(card['check_model'])}; the drawings are attached as bench-card-step-N.jpg.</p><ol>" +
                   "".join(f"<li>Step {c['step'] + 1}: bench-card-step-{c['step'] + 1}.jpg "
                           f"({'same scene' if c['faithful'] else 'differs: ' + e('; '.join(c['differences']))})</li>"
                           for c in card["steps"]) + "</ol>")
    return "".join(out)


def build(name, title, steps, files, rec, source=None, card=None, card_images=None, review=None, app_url="",
          created=None, modified=None):
    """files: {filename: bytes} of the run (protocol.py, methods.md, receipt.json, ...). card_images: {step: jpeg}.
    review: the reviewer agent's findings. Returns the .eln zip bytes."""
    root = f"show-dont-code-{name}"
    exp = f"./{name}/"
    files = dict(files)
    for i, jpg in sorted((card_images or {}).items()):
        files[f"bench-card-step-{i + 1}.jpg"] = jpg
    entities = [{"@id": exp + f, "@type": "File", "name": f, "encodingFormat": FORMATS.get(Path(f).suffix, "application/octet-stream"),
                 "contentSize": str(len(b)), "sha256": hashlib.sha256(b).hexdigest()} for f, b in sorted(files.items())]
    comments = [{"@id": f"#review-{k}", "@type": "Comment", "dateCreated": modified or _iso(),
                 "author": {"@id": "#reviewer-agent"},
                 "text": f"[{f.get('severity')}] steps {', '.join(str(s + 1) for s in f.get('steps', []))}: {f.get('finding')}"
                         + (f" Question: {f['question']}" if f.get("question") else "")}
                for k, f in enumerate(review or [])]
    upload = name.startswith("u-")
    licence = {"@id": "#no-license"} if upload else {"@id": CC_BY}
    experiment = {
        "@id": exp, "@type": "Dataset", "genre": "experiment", "name": title, "author": {"@id": AUTHOR},
        "dateCreated": created or _iso(), "dateModified": modified or _iso(),
        "keywords": ", ".join(["Opentrons Flex", "lab automation", "liquid handling", "Show Don't Code"] +
                              (["PCR"] if any(s.get("action") == "thermocycle" or "PCR" in (s.get("description") or "")
                                              for s in steps) or "pcr" in name else [])),
        "text": _body(name, steps, rec, source, card, app_url), "url": app_url, "license": licence,
        "hasPart": [{"@id": e["@id"]} for e in entities], "comment": [{"@id": c["@id"]} for c in comments],
    }
    if source and source.get("doi"):
        experiment["isBasedOn"] = {"@id": f"https://doi.org/{source['doi']}"}
    elif not upload:
        experiment["isBasedOn"] = {"@id": BIOVL2}
    graph = [
        {"@id": "ro-crate-metadata.json", "@type": "CreativeWork", "about": {"@id": "./"},
         "conformsTo": {"@id": RO12}, "dateCreated": _iso(),
         "sdPublisher": {"@id": REPO}},
        {"@id": RO12, "@type": ["CreativeWork", "Profile"], "name": "RO-Crate 1.2 Specification"},
        {"@id": ELN_SPEC, "@type": ["CreativeWork", "Profile"], "name": "ELN-File Format 1.2+20260923 Specification"},
        {"@id": "./", "@type": "Dataset", "name": f"Show, Don't Code: {title}", "datePublished": _iso(),
         "conformsTo": [{"@id": RO12}, {"@id": ELN_SPEC}],
         "description": "An Opentrons Flex protocol made from a lab protocol, with its checks, as one ELN experiment",
         "license": licence, "hasPart": [{"@id": exp}]},
        {"@id": REPO, "@type": "Organization", "name": "Show, Don't Code", "url": REPO},
        {"@id": AUTHOR, "@type": "Person", "name": "Pugar Huda Mantoro", "url": AUTHOR},
        {"@id": "#reviewer-agent", "@type": "SoftwareApplication", "name": "Reviewer agent (Muse Spark Open)",
         "url": "https://dev.meta.ai/models/muse-spark-open",
         "version": str(rec.get("models", {}).get("reviewer") or "")},
        ({"@id": "#no-license", "@type": "CreativeWork", "name": "No licence granted",
          "description": "The uploader's own video and what was derived from it; no reuse rights are given."}
         if upload else {"@id": CC_BY, "@type": "CreativeWork", "name": "CC BY 4.0"}),
        experiment, *entities, *comments,
    ]
    meta = {"@context": "https://w3id.org/ro/crate/1.2/context", "@graph": graph}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{root}/ro-crate-metadata.json", json.dumps(meta, indent=1, ensure_ascii=False))
        for f, b in sorted(files.items()):
            z.writestr(f"{root}/{name}/{f}", b)
    return buf.getvalue()
